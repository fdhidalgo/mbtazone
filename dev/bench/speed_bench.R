#!/usr/bin/env Rscript
# ============================================================================
# MCMC speed bench — fixed-seed, bit-identical correctness gate.
#
# Purpose: give a `/goal` loop an unambiguous, reward-hack-resistant signal for
# behavior-preserving (Class A) speedups of the parcel MCMC sampler. Each run
# prints a wall-clock time and a hash of the chain output. A correct speedup
# LOWERS the time while keeping the hash EQUAL to the captured baseline.
#
# It loads a pre-built warm targets store (no gpkg / pipeline rebuild needed),
# runs ONE chain twice with a fixed seed, and reports:
#   ELAPSED       min wall-clock of the run_parcel_chain_from_region() call (s)
#   OUTPUT_HASH   rlang::hash of the chain's parcel_samples
#   HASH_MATCH    OUTPUT_HASH == baseline hash (the correctness gate)
#   SPEEDUP       baseline_elapsed / ELAPSED
#
# Determinism is self-checked: the two runs must hash equal, or the bench FAILs
# (an optimization that introduced nondeterminism is a bug, not a speedup).
#
# Usage:
#   Rscript dev/bench/speed_bench.R              # measure + compare to baseline
#   Rscript dev/bench/speed_bench.R --capture    # (re)write baseline.txt
#
# DO NOT EDIT this file, baseline.txt, the seed, the step count, or the store
# while a speed goal is active — they define the measurement.
# ============================================================================

suppressMessages({ library(targets); library(igraph) })

# --- fixed measurement parameters (treat as frozen) -------------------------
PKG_ROOT <- Sys.getenv("MBTAZONE_PACKAGE_ROOT",
  unset = "/Users/dhidalgo/MIT Dropbox/Fernando Hidalgo/projects/mbta_communities/code/mbtazone")
STORE    <- file.path(PKG_ROOT, "ext", "_targets_Topsfield")
SEED     <- 42L
STEPS    <- 2000L      # > enrichment burn-in (1000) so online enrichment runs
RUNS     <- 2L         # repeats; ELAPSED = min, hashes must agree
BASELINE <- file.path(PKG_ROOT, "dev", "bench", "baseline.txt")

setwd(PKG_ROOT)
suppressMessages(pkgload::load_all(PKG_ROOT, quiet = TRUE,
                                   helpers = FALSE, attach_testthat = FALSE))
# Config constants are default-arg values resolved via base -> GlobalEnv.
source(file.path(PKG_ROOT, "inst/targets/temp_targets_config.R"))
source(file.path(PKG_ROOT, "inst/targets/temp_targets_parcel_config.R"))

stopifnot("warm store missing" = dir.exists(STORE))
tar_load(c(parcel_graph_result, constraints, discovered_secondary_library,
           discovered_lcc_library, parcel_initial_states, parcel_main_config),
         store = STORE)

cfg <- define_parcel_multichain_configs(
  base_config = parcel_main_config, n_chains = 1L,
  n_steps = STEPS, region_ids = "chain_1")[[1]]

run_once <- function() {
  set.seed(SEED)
  res <- suppressMessages(run_parcel_chain_from_region(
    config = cfg, parcel_graph_result = parcel_graph_result,
    constraints = constraints, secondary_library = discovered_secondary_library,
    lcc_library = discovered_lcc_library,
    initial_state = parcel_initial_states[[1]], verbose = FALSE))
  res$parcel_samples
}

elapsed <- numeric(RUNS); hashes <- character(RUNS)
for (i in seq_len(RUNS)) {
  t <- system.time(s <- run_once())[["elapsed"]]
  elapsed[i] <- t; hashes[i] <- rlang::hash(s)
}

deterministic <- length(unique(hashes)) == 1L
this_elapsed  <- min(elapsed)
this_hash     <- hashes[[1]]

# --- capture mode: write baseline and exit ----------------------------------
args <- commandArgs(trailingOnly = TRUE)
if ("--capture" %in% args) {
  git_hash <- tryCatch(trimws(system("git rev-parse --short HEAD", intern = TRUE)),
                       error = function(e) "unknown")
  writeLines(c(
    sprintf("baseline_hash=%s", this_hash),
    sprintf("baseline_elapsed=%.3f", this_elapsed),
    sprintf("store=%s", basename(STORE)),
    sprintf("seed=%d", SEED),
    sprintf("steps=%d", STEPS),
    sprintf("git_commit=%s", git_hash)
  ), BASELINE)
  cat(sprintf("\nBASELINE CAPTURED -> %s\n", BASELINE))
  cat(sprintf("baseline_hash=%s\nbaseline_elapsed=%.3f\ndeterministic=%s\n",
              this_hash, this_elapsed, deterministic))
  quit(save = "no")
}

# --- compare mode -----------------------------------------------------------
base <- if (file.exists(BASELINE)) {
  kv <- strsplit(readLines(BASELINE), "=")
  setNames(vapply(kv, `[`, "", 2), vapply(kv, `[`, "", 1))
} else NULL

cat(sprintf("\n=== MCMC SPEED BENCH (%s, seed=%d, steps=%d, runs=%d) ===\n",
            basename(STORE), SEED, STEPS, RUNS))
cat(sprintf("ELAPSED: %.2f\n", this_elapsed))
cat(sprintf("OUTPUT_HASH: %s\n", this_hash))
cat(sprintf("DETERMINISTIC: %s\n", deterministic))
if (!is.null(base)) {
  base_hash <- base[["baseline_hash"]]; base_el <- as.numeric(base[["baseline_elapsed"]])
  hash_match <- identical(this_hash, base_hash)
  cat(sprintf("BASELINE_HASH: %s\n", base_hash))
  cat(sprintf("BASELINE_ELAPSED: %.2f\n", base_el))
  cat(sprintf("HASH_MATCH: %s\n", hash_match))
  cat(sprintf("SPEEDUP: %.3fx\n", base_el / this_elapsed))
  if (!deterministic)
    cat("NOTE: non-deterministic output across runs — this is a correctness bug.\n")
} else {
  cat("BASELINE: (none — run with --capture first)\n")
}
